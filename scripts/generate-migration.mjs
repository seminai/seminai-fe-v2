import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { parse } from "yaml";
import { PUBLIC_PAGES } from "../src/config/publicPages.ts";
const origin = "https://seminai.tech";
const routes = [
  "/",
  "/en/",
  "/privacy-policy/",
  "/cookie-policy/",
  "/terms-of-service/",
  "/richiedi-demo/",
  "/en/request-a-demo/",
  ...PUBLIC_PAGES.map((page) => page.path),
  "/news/",
  "/en/news/",
];
const redirects = {
  "/hub/": "/risorse/",
  "/hub/about/": "/chi-siamo/",
  "/hub/blog/": "/news/",
  "/hub/en/blog/": "/en/news/",
  "/hub/rules/": "/regole/",
  "/hub/sitemap-index.xml": "/sitemap.xml",
  "/hub/sitemap-0.xml": "/sitemap.xml",
};
const categories = [
  "disciplinare",
  "standard",
  "best_practice",
  "methodology",
  "custom",
];
for (const category of categories)
  redirects[`/hub/rules/category/${category}/`] =
    `/regole/categoria/${category}/`;
const articles = [];
for (const lang of ["it", "en"])
  for (const file of readdirSync(`src/content/news/${lang}`).filter((f) =>
    f.endsWith(".mdx"),
  )) {
    const raw = readFileSync(`src/content/news/${lang}/${file}`, "utf8");
    const meta = parse(raw.match(/^---\n([\s\S]*?)\n---/)[1]);
    const slug = file.slice(0, -4);
    const path = `${lang === "en" ? "/en" : ""}/news/${slug}/`;
    routes.push(path);
    articles.push({ lang, slug, path, translationKey: meta.translationKey });
    redirects[`/hub/${lang === "en" ? "en/" : ""}blog/${slug}/`] = path;
  }
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? walk(`${dir}/${entry.name}`)
      : [`${dir}/${entry.name}`],
  );
}
for (const file of walk("public/legacy-hub-assets"))
  redirects[`/hub/${file.slice("public/legacy-hub-assets/".length)}`] =
    file.slice("public".length);
const markdown = {};
for (const route of routes)
  markdown[route] =
    route === "/"
      ? "/index.md"
      : route === "/en/"
        ? "/index.en.md"
        : `${route.replace(/\/$/, "")}.md`;
mkdirSync("config", { recursive: true });
writeFileSync(
  "config/public-site.json",
  JSON.stringify({ origin, routes, markdown, redirects, articles }, null, 2) +
    "\n",
);
const rows = Object.entries(redirects)
  .map(([from, to]) => `| \`${from}\` | \`${to}\` | 301 |`)
  .join("\n");
mkdirSync("docs", { recursive: true });
writeFileSync(
  "docs/SEO_GEO_URL_MAP.md",
  `# Public-site migration map\n\nGenerated by scripts/generate-migration.mjs. Source host: app.seminai.tech. Target host: seminai.tech. Query strings are preserved. Unlisted blog paths return 404; rule details keep their public API slug.\n\n| Source path | Target path | Status |\n|---|---|---|\n${rows}\n\nDynamic mapping: /hub/rules/<slug>/ → /regole/<slug>/. Validate all published slugs against the anonymous API before cutover. Unknown destination slugs return 404. Retain redirects indefinitely.\n\nRun node scripts/inventory-public-rules.mjs > /tmp/seminai-public-rule-map.json before cutover to capture every published slug and original document URL. The command emits no partial map on failure. For synthetic validation set HUB_API_BASE_URL=http://127.0.0.1:9876.\n`,
);
console.log(
  `Migration: ${Object.keys(redirects).length} exact redirects, ${routes.length} static routes`,
);
